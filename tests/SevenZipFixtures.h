/// A 140 KB disk with a mark at the head of every page (the page number,
/// then $A5); side B differs from side A at byte 5.
inline std::vector<std::uint8_t> sevenZipFixtureDisk(char side)
{
    std::vector<std::uint8_t> d(143360, 0);
    for (std::size_t i = 0; i < d.size(); i += 256) {
        d[i] = static_cast<std::uint8_t>((i / 256) & 0xFF);
        d[i + 1] = 0xA5;
    }
    if (side == 'B') d[5] = 0x42;
    return d;
}

