const KeyboardSkin& keyboardSkin(SystemProfile profile) {
    static const KeyboardSkin iie{"pic/Keyboard_AppleIIe.jpeg", "Apple //e Keyboard", appleIIeKeyboard()};
    static const KeyboardSkin iic{"pic/Keyboard_AppleIIc.png", "Apple //c Keyboard", appleIIcKeyboard(), true,
                                  2578.0f / 908.0f};
    switch (profile) {
    case SystemProfile::AppleIIc:
    case SystemProfile::AppleIIcPAL:
    case SystemProfile::AppleIIcPlus: return iic;
    default: return iie;
    }
}
